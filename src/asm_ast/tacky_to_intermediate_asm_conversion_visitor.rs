//
// Converts or lowers a TACKY application into an target-agnostic, intermediary, pseudo
// ASM AST (of precursor/pseudo ASM instructions).
//
// The TACKY code is generated by the TackyVisitor.
// Target-Ready assembly code is generated by asm_ast_gas_emitter_visitor.rs or asm_ast_masm_emitter_visitor.rs.
//
// 1. src\c_ast\IdentifierResolutionVisitor - checks for duplicate or undeclared variable names
// 2. src\c_ast\type_checking_visitor.rs - type checking
// 3. tacky/TackyVisitor - Generate TACKY (from AST)
// 4. src\asm_ast\tacky_to_intermediate_asm_conversion_visitor.rs - (This struct) Converts TACKY into a ASM AST for assembly with a precursory form of mnenomics
// 5. asm_ast/AsmAstFixupVisitor - replacing pseudo operands/variables with stack addresses
// 6. asm_ast/AsmAstMasmEmitterVisitor / asm_ast/AsmAstGASEmitterVisitor / ...
//
// This visitor generates a precursory form of real assembly instructions.
// For each indidivual line of TACKY instruction, it prepares one or more precursor assembly instructions
// that are required to execute functionality that the TACKY instruction hints at.
//
// e.g. div, remainder/module, mul, ... need to arrange parameters and execute data type
// conversion (cdq, ...) before finally executing the arithmetic mnemonic. This visitor
// will prepare all the pseudo mnemonics required to execute each TACKY function/line.
//

