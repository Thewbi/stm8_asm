    pub fn visit_tacky_program(&mut self, tacky_node_program: &Program)
    {
        // DEBUG
        // println!("[TackyToIntermediateAsmConversionVisitor::visit_tacky_program()]");

        self.asm_ast_program.name = tacky_node_program.name.clone();

        for i in 0..tacky_node_program.top_level.len() {

            let temp_top_level_item: &Box<TopLevel> = &tacky_node_program.top_level[i];
            match &temp_top_level_item.as_ref().top_level_type {

                TopLevelType::Scope | TopLevelType::Function => {
                    self.visit_tacky_function(&temp_top_level_item.as_ref());
                }

                TopLevelType::StaticVariable => {
                    todo!("TopLevelType::StaticVariable");
                }

                TopLevelType::StaticConstant => {
                    todo!("TopLevelType::StaticConstant");
                }
            }
        }
    }

    pub fn visit_tacky_function(&mut self,
        tacky_node_top_level_function: &TopLevel)
    {
        let function_name = tacky_node_top_level_function.name.clone();

        // DEBUG
        if self.debug {
            println!("[TackyToIntermediateAsmConversionVisitor::visit_tacky_function()] '{}'",
                &function_name);
        }

        let mut asm_ast_function: AsmAstFunction = AsmAstFunction::new();

        //
        // Function Name
        //

        asm_ast_function.name = function_name.clone();
        if tacky_node_top_level_function.return_type.is_some() {
            asm_ast_function.return_type =
                Some(tacky_node_top_level_function.return_type.clone().expect("REASON"));
        }

        // ALLOCATE_STACK instruction
        //
        // insert allocate stack instruction - page 42
        //
        // Placeholder to reserve space for local variables.
        //
        // This instruction is later updated inside the
        // AsmAstFixupVisitor::visit_asm_ast_function() call
        let mut asm_ast_allocate_stack: AsmAstInstruction = AsmAstInstruction::new();
        asm_ast_allocate_stack.instruction_type = AsmAstInstructionType::AllocateStack;
        asm_ast_allocate_stack.src.operand_type = AsmAstOperandType::Imm(0);
        asm_ast_allocate_stack.comment = String::from("\n    ; Function Preamble - save space on stack for all local variables - [AsmAstConversionVisitor::visit_tacky_function()]");
        asm_ast_function.body.push(Box::new(asm_ast_allocate_stack));

        // DESCRIPTION
        //
        // Nora Sandler, page 196
        //
        // Copy all function parameters which are located in registers onto the stack
        // so that there is no need to store and restore registers to keep the parameters
        // alive as the function executes.
        //
        // (System-V ABI, the first six registers ("DI", "SI", "DX", "CX", "R8", "R9")
        // and Win64 FastCall, the first 4 registers (RCX, RDX, R8 and R9))
        //
        // To achieve this, the amount of parameters has to be known and move-instructions
        // to stack addresses need to be emitted.
        //
        // How to formulate the stack addresses?
        //

        // // DEBUG
        // println!("Function {:?} has {} formal arguments!", &function_name, tacky_node_top_level_function.arguments.len());
        // println!("SYSTEM_V_ABI_REGISTER_ORDER: {:?}", SYSTEM_V_ABI_REGISTER_ORDER);

        // DEBUG
        if self.debug {
            println!("[T2IASM] {:?}", tacky_node_top_level_function);
            //println!("[T2IASM] {:?}", tacky_node_top_level_function.arguments);
        }

        // move parameters, which have been passed in via registers, onto the stack
        for (i, param) in tacky_node_top_level_function.arguments.iter().enumerate() {

            // asm_ast_function.formal_parameters.push(param.data_type.clone());

            // only process arguments 0 to REGISTER_COUNT-1,
            // the rest of the arguments is on the stack already
            if i >= REGISTER_COUNT {
                continue;
            }

            if param.data_type == DataType::DataTypeUnknown {
                panic!("Need a type");
            }

            // exclude void
            if param.data_type == DataType::DataTypeVoid {
                continue;
            }

            // DEBUG
            if self.debug {
                println!("Parameter {:?}) {:?} is located in register {:?}",
                    i, param, REGISTER_ORDER[i]);
            }

            // TODO: generate move commands for each of the first n ABI
            // registers into a stack address!

            // TODO: where and how are the stack addresses computed?

            // this function is part of the AsmAstConversionVisitor (this struct)
            // which is followed by the AsmAstFixupVisitor.
            // The AsmAstFixupVisitor has the purpose of generating addresses for
            // AsmAstOperandType::Pseudo defined in asm_ast.rs

            let mut symbol_table_entry = self.symbol_table.borrow_mut().get(&param.name.clone()).unwrap();

            // DEBUG
            if self.debug {
                println!("[T2InterASM] symbol_table_entry {:?}", symbol_table_entry);
            }

            assert_ne!(symbol_table_entry.data_type, DataType::DataTypeUnknown);

            // // because of pointer dereference problems when passed as parameters
            // // into a function, register here if a parameter is a pointer and the
            // // pointer is then moved into memory
            // match symbol_table_entry.data_type {
            //     DataType::DataTypePointer(_) => {
            //         symbol_table_entry.symbol_table_entry_type
            //             = SymbolTableEntryType::PointerInMemory;
            //     }
            //     _ => {
            //     }
            // }

            // because of pointer dereference problems when passed as parameters
            // into a function, register here if a parameter is a pointer and the
            // pointer is then moved into memory
            if symbol_table_entry.is_pointer {
                symbol_table_entry.symbol_table_entry_type
                        = SymbolTableEntryType::PointerInMemory;
            }

            self.symbol_table.borrow_mut().insert(param.name.clone(), symbol_table_entry);

            //
            // Mov - move from register (where the parameter lives) to the stack
            //

            let mut mov: AsmAstInstruction = AsmAstInstruction::new();
            mov.instruction_type = AsmAstInstructionType::Mov;
            mov.comment = String::from(format!("    ; INSIDE_FUNCTION. Moving Reg-To-MEM: Parameter {:?}) {:?} is located in register {:?}", i, param, REGISTER_ORDER[i]).to_string());
            mov.src = AsmAstOperand{ operand_type: AsmAstOperandType::Reg(REGISTER_ORDER[i].clone()) };
            mov.dst = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(param.name.clone()) };
            mov.assembly_type = AstAstAssemblyType::from_data_type(&param.data_type);

            // insert the generated local variable into the symbol table otherwise
            // the asm_ast_fixup_visitor cannot retrieve it from the symbol table when
            // it processes the Pseudo ASM line generated above which copies the parameter
            // from the register into a local variable

            asm_ast_function.body.push(Box::new(mov));
        }

        //
        // BODY
        //

        // emit all instructions in the body
        for i in 0..tacky_node_top_level_function.body.len() {

            let tacky_instruction: &Instruction = &tacky_node_top_level_function.body[i].as_ref();

            // DEBUG
            if self.debug {
                println!("[visit_tacky_function] {:?}", &tacky_instruction);
            }

            match tacky_instruction.instruction_type {

                InstructionType::Comment => {
                    // do nothing
                }

                InstructionType::Unary => {
                    self.visit_tacky_unary(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::Binary => {
                    self.visit_tacky_binary(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::Break => {
                    //self.visit_tacky_break(&mut asm_ast_function, tacky_instruction);

                    // DEBUG
                    if tacky_instruction.id == 123 {
                        println!("[T2IASM] Break. test");
                    }

                    if tacky_instruction.label.len() == 0 {
                        panic!("Need label!");
                    }

                    // break
                    let mut break_instruction: AsmAstInstruction = AsmAstInstruction::new();
                    break_instruction.instruction_type = AsmAstInstructionType::Break;
                    break_instruction.dst
                        = AsmAstOperand {
                            operand_type: AsmAstOperandType::Label(tacky_instruction.label.clone()) };

                    asm_ast_function.body.push(Box::new(break_instruction));
                }

                InstructionType::Return => {
                    self.visit_tacky_return(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::JumpIfZero => {
                    self.visit_tacky_jump_if_zero(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::Label => {
                    self.visit_tacky_label(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::VariableDeclaration => {
                    self.visit_tacky_variable_declaration(tacky_instruction);
                }

                InstructionType::Copy => {
                    self.visit_tacky_copy(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::Jump => {
                    self.visit_tacky_jump(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::FunCall => {
                    self.visit_tacky_fun_call_system_v_abi(
                        &mut asm_ast_function,
                        tacky_instruction);
                }

                InstructionType::GetAddress => {
                    self.visit_tacky_get_address(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::Load => {
                    self.visit_tacky_load(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::Store => {
                    self.visit_tacky_store(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::SignExtend => {
                    self.visit_tacky_sign_extend(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::Truncate => {
                    self.visit_tacky_truncate(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::CopyToOffset => {
                    self.visit_tacky_copy_to_offset(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::CopyFromOffset => {
                    self.visit_tacky_copy_from_offset(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::CopyFromOffsetPointerDeref => {
                    self.visit_tacky_copy_from_offset_ptr_deref(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::AddAssignment => {
                    self.visit_tacky_add_assignment(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::SubAssignment => {
                    self.visit_tacky_sub_assignment(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::MulAssignment => {
                    self.visit_tacky_mul_assignment(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::RightShiftAssignment => {
                    self.visit_tacky_right_shift_assignment(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::SubscriptSrc => {
                    //
                    // CASE 1 - subscript is src of assignment:
                    // EXAMPLE: i = arr[1];
                    //
                    self.visit_tacky_subscript_src(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::SubscriptDst => {
                    //
                    // CASE 2 - subscript is dst of assignment
                    // EXAMPLE: arr[0] = 123;
                    //
                    self.visit_tacky_subscript_dst(&mut asm_ast_function, tacky_instruction);
                }

                InstructionType::InlineAssembly => {

                    // println!("{:?}", tacky_instruction.src);

                    let mut instruction: AsmAstInstruction = AsmAstInstruction::new();
                    instruction.instruction_type = AsmAstInstructionType::InlineAssembly;
                    instruction.assembly_type = AstAstAssemblyType::Unknown;

                    match &tacky_instruction.src {
                        ValueElement::Constant(string_val) => {
                            instruction.src = AsmAstOperand { operand_type: AsmAstOperandType::ImmString(string_val.clone()) };
                        }
                        _ => {
                            todo!();
                        }
                    }

                    // instruction.dst = AsmAstOperand {
                    //     operand_type: AsmAstOperandType::Reg(AsmAstReg::RAX)
                    // };
                    // match instruction.src.clone() {
                    //     ValueElement::Constant(constant_value) => {
                    //         let value: i32 = i32::from_str_radix(&constant_value, 10).expect("REASON");
                    //         sar_instruction.src = AsmAstOperand {
                    //             operand_type: AsmAstOperandType::Imm(value)
                    //         };
                    //     }
                    //     _ => {
                    //         todo!();
                    //     }
                    // }
                    // assert_ne!(sar_instruction.assembly_type, AstAstAssemblyType::Unknown);
                    // println!("sar_instruction: {:?}", sar_instruction);
                    asm_ast_function.body.push(Box::new(instruction));
                }

                _ => {
                    panic!("{}", format!("Unhandled InstructionType {:?}!\n", tacky_instruction.instruction_type).as_str());
                }
            }
        }

        //
        // deallocate stack - deallocating the stack is done after
        // the function call instruction is emitted inside
        // visit_tacky_fun_call_system_v_abi()
        //

        // let mut deallocate_stack: AsmAstInstruction = AsmAstInstruction::new();
        // deallocate_stack.instruction_type = AsmAstInstructionType::DeallocateStack;
        // deallocate_stack.src.operand_type = AsmAstOperandType::Imm(120 as i32);

        // asm_ast_function.body.push(Box::new(deallocate_stack));

        // add the created function into the functions vector of the program
        self.asm_ast_program.functions.push(asm_ast_function);
    }

    pub fn visit_tacky_subscript_src(&mut self,
        asm_ast_function: &mut AsmAstFunction,
        tacky_instruction_subscript: &Instruction)
    {
        //
        // CASE 1 - subscript is src of assignment:
        // EXAMPLE: i = arr[1];
        //

        // DEBUG
        if self.debug {
            println!("{:?}", tacky_instruction_subscript);
        }

        let mut element_data_type: DataType = DataType::DataTypeUnknown;

        //
        // retrieve the data type of the array elements
        //

        match &tacky_instruction_subscript.data_type {
            DataType::DataTypeArray(inner_data_type, array_element_count) => {
                element_data_type = *inner_data_type.clone();
            }
            DataType::DataTypeChar |
            DataType::DataTypeInt => {
                element_data_type = tacky_instruction_subscript.data_type.clone();
            }
            _ => {
                panic!("Unhandled type: {:?}", &tacky_instruction_subscript.data_type);
            }
        }
        assert_ne!(element_data_type, DataType::DataTypeUnknown,
            "Need a inner element data type!");

        let mut pointer_in_memory: bool = false;

        match &tacky_instruction_subscript.src {
            ValueElement::Variable(var_name) => {
                // retrieve address
                let symbol_table_entry_option = self.symbol_table.borrow_mut().get(var_name).unwrap();
                // println!("symbol_table_entry_option: '{:?}'", &symbol_table_entry_option);
                // println!("");
                pointer_in_memory = symbol_table_entry_option.symbol_table_entry_type == SymbolTableEntryType::PointerInMemory;
            }
            _ => {

            }
        }

        let offset_register_dword = AsmAstReg::EAX;
        let offset_register_qword = AsmAstReg::RAX;

        //
        // clear rax -- xor rax, rax
        //

        let mut xor: AsmAstInstruction = AsmAstInstruction::new();
        xor.instruction_type = AsmAstInstructionType::Xor;
        xor.assembly_type = AstAstAssemblyType::Quadword;
        xor.src = AsmAstOperand { operand_type: AsmAstOperandType::Reg(offset_register_qword.clone()) };
        xor.dst = AsmAstOperand { operand_type: AsmAstOperandType::Reg(offset_register_qword.clone()) };
        assert_ne!(xor.assembly_type, AstAstAssemblyType::Unknown);
        asm_ast_function.body.push(Box::new(xor));

        //
        // Subscript 1 -- move the array indexer into eax
        // 0. mov
        //
        // if the variable is subscripted using a index variable (such as i for for loops)
        // then this index variable i needs to be part of the subscript address computation.
        //
        // Therefore the variable needs to be transferred into a register in order to formulate
        // asm instructions such as:
        //
        // ```
        // mov eax, dword ptr [rbp-28-rax*4]
        // ```
        //
        // mov_index will move the index into rax to satisfy the instruction above
        //

        let mut mov_index: AsmAstInstruction = AsmAstInstruction::new();
        mov_index.instruction_type = AsmAstInstructionType::Mov;
        let index_data_type: AstAstAssemblyType;
        mov_index.comment = String::from("    ; [visit_tacky_subscript_src() - Subscript 1] Mov Index/Offset into RAX");
        // the index into the array is stored in tacky_instruction_subscript.index.
        // move this index into EAX
        match &tacky_instruction_subscript.index {
            ValueElement::Variable(var_name) => {
                // retrieve address
                let symbol_table_entry_option = self.symbol_table.borrow_mut().get(var_name);
                let symbol_table_entry = symbol_table_entry_option.expect(format!("No symbol for '{}' found in symbol table!\n", var_name).as_str());
                index_data_type = AstAstAssemblyType::from_data_type(&symbol_table_entry.data_type);
                mov_index.src = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                mov_index.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
            }
            ValueElement::Constant(literal_value) => {
                index_data_type = AstAstAssemblyType::Doubleword;
                // TODO: convert base on number system (binary, octal, decimal, hexadecimal)!
                // ERROR: Currently hard-coded!
                let val = i32::from_str_radix(&literal_value, 10).expect("REASON");
                // val = val * 4; // TODO DataType determins into 4
                mov_index.src = AsmAstOperand { operand_type: AsmAstOperandType::Imm(val.clone()) };
                mov_index.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Imm(val.clone()) };
            }
            _ => {
                panic!("[ERR] Unhandled type: {:?}", &tacky_instruction_subscript.index);
            }
        }
        mov_index.dst = AsmAstOperand { operand_type: AsmAstOperandType::Reg(offset_register_dword.clone()) };
        mov_index.assembly_type = index_data_type;
        assert_ne!(mov_index.assembly_type, AstAstAssemblyType::Unknown);
        asm_ast_function.body.push(Box::new(mov_index));

        // DEBUG
        //println!("mov_index.assembly_type: {:?}", mov_index.assembly_type);

        //
        // Subscript 2
        // 1. Mov = Mov(Quadword, ptr, Reg(AX))
        //
        // This is where the array is accessed using a base pointer and an index!
        // The pointer-index/offset is expected in EAX and the result of the
        // array subscript access is then written into EAX.
        //
        // If you treat this mov as a function, then the function has a parameter
        // which is EAX and it places the return value into EAX!
        //
        // Write the basepointer into register A because register A is used
        // in register relative addressing in the second mov instruction later
        //
        // Perform register relative addressing relativ to the base address
        // stored inside the register A
        //

        // AST after type-checking is the same for both options
        // TACKY is the same for both options
        // Intermediate AST differs

        // let var_val;
        // match &tacky_instruction_subscript.src {
        //     ValueElement::Variable(var_name) => {
        //         self.variable_naming_source.borrow_mut().print_variable_naming_source();
        //         println!("[T2IASM] var_name: '{:?}'", var_name);
        //         var_val = self.variable_naming_source.borrow_mut().get_replaced_variable_name(var_name);
        //     }
        //     _ => {
        //         println!("test");
        //     }
        // }

        if pointer_in_memory {

            /* START START START */

            //
            // emits:
            // mov rbx, qword ptr [rbp+-408]
            // mov eax, dword ptr[rbx+rax*4]
            //
            // this works for
            // res\C\samples\c_samples\strlen_0.c
            // res\C\samples\c_samples\function_call_5.c
            //
            // Where the array (or const string literal) is accessed via a
            // function parameter which contains a pointer (address) to the
            // first element of the array.
            //
            // A construct is required, where in the first step the function
            // parameter needs to be dereferenced into a pointer. Then in a
            // second step, the pointer can be offset by an index to an element
            // multiplied by the element size.
            //

            // step 1 - turn the function parameter into the pointer (base address) to the array
            let mut mov_1: AsmAstInstruction = AsmAstInstruction::new();
            mov_1.instruction_type = AsmAstInstructionType::Mov;
            mov_1.assembly_type = AstAstAssemblyType::from_data_type(&DataType::DataTypeLong); // pointers are DataTypeLong on x64
            mov_1.comment = String::from(format!("    ; [visit_tacky_subscript_src() - Subscript 2] dereference pointer").to_string());
            match &tacky_instruction_subscript.src {
                ValueElement::Variable(var_name) => {
                    // DEBUG
                    if self.debug {
                        println!("{:?}", var_name);
                    }
                    mov_1.src = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                    mov_1.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                }
                ValueElement::Constant(constant_value) => {
                    mov_1.src = AsmAstOperand { operand_type: AsmAstOperandType::Imm(i32::from_str_radix(&constant_value, 10).expect("REASON")) };
                }
                _ => {
                    panic!("Need variable or constant! Got {:?}", &tacky_instruction_subscript.src);
                }
            }
            mov_1.dst = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::RBX) };
            assert_ne!(mov_1.assembly_type, AstAstAssemblyType::Unknown);
            asm_ast_function.body.push(Box::new(mov_1));

            // step 2 apply the element offset multiplied by element size to the base address
            let mut mov_1_2: AsmAstInstruction = AsmAstInstruction::new();
            mov_1_2.instruction_type = AsmAstInstructionType::Mov;
            mov_1_2.assembly_type = AstAstAssemblyType::from_data_type(&element_data_type);
            mov_1_2.comment = String::from(format!("    ; [visit_tacky_subscript_src() - Subscript 2] mov_1_2 dereference pointer").to_string());
            mov_1_2.src = AsmAstOperand { operand_type: AsmAstOperandType::BaseRegWithOffsetAndSize(AsmAstReg::RBX, AsmAstReg::RAX, element_data_type.get_size(&self.type_system.borrow()) as i32) };
            mov_1_2.dst = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::RAX) };
            assert_ne!(mov_1_2.assembly_type, AstAstAssemblyType::Unknown);
            asm_ast_function.body.push(Box::new(mov_1_2));

            // END END END END

        } else {

            /* START START START */

            //
            // emits:
            // mov eax, dword ptr [rbp-408+rax*4]
            //
            // this works for
            // res\C\samples\c_samples\fread_0.c
            // res\C\samples\c_samples\array_0.c
            // res\C\samples\c_samples\array_8.c
            //
            // where the array is a 'local variable' !!!
            // The address is the address of a local array inside the current stack frame.
            //
            // A construct like: mov al, byte ptr [rbp-8+rax*1]
            // which combines the start address and an element offset is required!
            //

            let mut mov_1: AsmAstInstruction = AsmAstInstruction::new();
            mov_1.instruction_type = AsmAstInstructionType::Mov;
            mov_1.assembly_type = AstAstAssemblyType::from_data_type(&element_data_type);
            mov_1.comment = String::from(format!("    ; [visit_tacky_subscript_src() - Subscript 2] for subscript (applying an index to an array)").to_string());
            match &tacky_instruction_subscript.src {
                ValueElement::Variable(var_name) => {
                    // DEBUG
                    if self.debug {
                        println!("{:?}", var_name);
                    }
                    mov_1.src = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                    mov_1.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                }
                ValueElement::Constant(constant_value) => {
                    mov_1.src = AsmAstOperand { operand_type: AsmAstOperandType::Imm(i32::from_str_radix(&constant_value, 10).expect("REASON")) };
                }
                _ => {
                    panic!("Need variable or constant! Got {:?}", &tacky_instruction_subscript.src);
                }
            }
            match &tacky_instruction_subscript.dst {
                ValueElement::Variable(var_name) => {
                    // DEBUG
                    if self.debug {
                        println!("{:?}", var_name);
                    }
                    mov_1.dst = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::EAX) };
                }
                _ => {
                    panic!("Need variable! Got {:?}", &tacky_instruction_subscript.src);
                }
            }
            mov_1.offset = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::RAX) };
            assert_ne!(mov_1.assembly_type, AstAstAssemblyType::Unknown);
            asm_ast_function.body.push(Box::new(mov_1));

            // END END END END
        }

        //
        // Subscript 3
        // 2. Mov = Mov(<dst_type>, Memory(AX, 0), dst)
        //
        // Move the value retrieved from the array which is located in register A
        // into the destination memory location
        //

        let mut mov_2: AsmAstInstruction = AsmAstInstruction::new();
        mov_2.instruction_type = AsmAstInstructionType::Mov;
        mov_2.assembly_type = AstAstAssemblyType::from_data_type(&element_data_type);
        mov_2.comment = String::from("    ; [visit_tacky_subscript_src() - Subscript 3] mov_2");
        // determine src of mov
        match &tacky_instruction_subscript.dst {
            ValueElement::Variable(var_name) => {
                mov_2.src = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::EAX) };
                // mov_2.src = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::RAX) };

                //mov_2.src = AsmAstOperand { operand_type: AsmAstOperandType::DerefReg(AsmAstReg::RAX) };
            }
            ValueElement::Constant(constant_value) => {
                mov_2.src = AsmAstOperand { operand_type: AsmAstOperandType::Imm(i32::from_str_radix(&constant_value, 10).expect("REASON")) };
            }
            _ => {
                panic!("Need variable or Constant! Got {:?}", &tacky_instruction_subscript.src);
            }
        }
        // determine destination of mov
        // changed to dst for array_4.c
        match &tacky_instruction_subscript.dst {
            ValueElement::Variable(var_name) => {
                mov_2.dst = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
            }
            _ => {
                panic!("[ERR] Need variable!");
            }
        }
        assert_ne!(mov_2.assembly_type, AstAstAssemblyType::Unknown);
        asm_ast_function.body.push(Box::new(mov_2));
    }

    pub fn visit_tacky_subscript_dst(&mut self,
        asm_ast_function: &mut AsmAstFunction,
        tacky_instruction_subscript: &Instruction)
    {
        // the destination of the instruction is a subscripted array
        // e.g. arr[0] = 123;
        // e.g. arr[0] = a;

        //
        // CASE 2 - array subscript is destination of assignment
        // EXAMPLE: arr[0] = 123;
        // EXAMPLE: arr[0] = a;
        //

        // DEBUG
        if self.debug {
            println!("tacky_instruction_subscript: {:?}", tacky_instruction_subscript);
        }

        let offset_register = AsmAstReg::RAX;

        //
        // if the variable is subscripted using a index variable (such as i for for-loops)
        // then this index variable i needs to be part of the subscript address computation.
        //
        // Therefore the variable needs to be transferred into a register in order to formulate
        // asm instructions such as: mov eax, dword ptr [rbp-28+rax*4]
        //

        let mut mov_index: AsmAstInstruction = AsmAstInstruction::new();
        mov_index.instruction_type = AsmAstInstructionType::Mov;
        mov_index.assembly_type = AstAstAssemblyType::Doubleword;
        mov_index.comment = String::from("    ; [visit_tacky_subscript_dst() - Subscript 1] Mov Index/Offset into RAX");

        // the index into the array is stored in tacky_instruction_subscript.index.
        // move this index into EAX
        let mut src_data_type: DataType = DataType::DataTypeUnknown;
        match &tacky_instruction_subscript.index {

            ValueElement::Variable(var_name) => {
                let symbol_table_entry_option = self.symbol_table.borrow_mut().get(var_name);
                let symbol_table_entry: SymbolTableEntry = symbol_table_entry_option.expect(format!("No symbol for '{}' found in symbol table!\n", var_name).as_str());
                src_data_type = symbol_table_entry.data_type;

                mov_index.src = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                mov_index.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
            }

            ValueElement::Constant(literal_value) => {
                // println!("literal_value: {:?}", literal_value);

                src_data_type = tacky_instruction_subscript.data_type.clone();

                // TODO: convert base on number system
                // (binary, octal, decimal, hexadecimal! Currently hard-coded!)
                let array_index = i32::from_str_radix(&literal_value, 10).expect("REASON");
                mov_index.src = AsmAstOperand { operand_type: AsmAstOperandType::Imm(array_index.clone()) };
                mov_index.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Imm(array_index.clone()) };
            }

            _ => {
                panic!("[ERR] Unhandled type: {:?}", &tacky_instruction_subscript.index);
            }
        }
        mov_index.dst = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::EAX) };

        // println!("[Tacky2Inter][visit_tacky_subscript_dst] src_data_type: {:?}", src_data_type);

        assert_ne!(mov_index.assembly_type, AstAstAssemblyType::Unknown);
        asm_ast_function.body.push(Box::new(mov_index));

        //
        // 1. Mov = Mov(Quadword, ptr, Reg(AX))
        //
        // This is where the array is accessed using a base pointer and an index!
        // The pointer-index/offset is expected in EAX and the result of the
        // array subscript access is then written into EAX.
        //
        // If you treat this mov as a function, then the function has a parameter
        // which is EAX and it places the return value into EAX!
        //
        // Write the basepointer into register A because register A is used
        // in register relative addressing in the second mov instruction later
        //
        // Perform register relative addressing relativ to the base address
        // stored inside the register A
        //

        let mut mov_1: AsmAstInstruction = AsmAstInstruction::new();
        mov_1.instruction_type = AsmAstInstructionType::Mov;
        mov_1.comment = String::from(format!("    ; [visit_tacky_subscript_dst() - Subscript 2] for subscript (applying an index to an array)").to_string());
        //mov_1.assembly_type = AstAstAssemblyType::from_data_type(&tacky_instruction_subscript.data_type);

        match &tacky_instruction_subscript.data_type {
            DataType::DataTypeArray(inner_element_data_type, array_element_count) => {
                mov_1.assembly_type = AstAstAssemblyType::from_data_type(&inner_element_data_type);
            }
            _ => {
                panic!("Only array expected in subscript!");
            }
        }

        // src is the literal value or variable to transfer into the array
        match &tacky_instruction_subscript.src {
            ValueElement::Variable(var_name) => {
                // DEBUG
                if self.debug {
                    println!("{:?}", var_name);
                }
                // add a mov instruction which moves the variable's value into ECX
                // mov ecx, dword ptr [rbp-48]
                let mut mov_4: AsmAstInstruction = AsmAstInstruction::new();
                mov_4.instruction_type = AsmAstInstructionType::Mov;
                mov_4.assembly_type = AstAstAssemblyType::Doubleword;
                mov_4.comment = String::from(format!("    ; [visit_tacky_subscript_dst() - Subscript 4] mov src variable's value into dst!").to_string());
                // ECX was choosen at random. There is no reason. Could use any free register.
                mov_4.src = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                mov_4.dst = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::ECX) };
                assert_ne!(mov_4.assembly_type, AstAstAssemblyType::Unknown);
                asm_ast_function.body.push(Box::new(mov_4));
                mov_1.src = AsmAstOperand { operand_type: AsmAstOperandType::Reg(AsmAstReg::ECX) };
            }
            ValueElement::Constant(constant_value) => {

                // println!("constant_value: '{}'", constant_value);

                if constant_value.starts_with("'") {
                    let constant_value = rem_first_and_last(constant_value);
                    let char_constant_value: char = constant_value.chars().next().unwrap();
                    let converted_value: i32 = char_constant_value as i32;
                    mov_1.src =
                        AsmAstOperand {
                            operand_type: AsmAstOperandType::Imm(converted_value)
                        };
                } else {
                    let converted_value = i32::from_str_radix(&constant_value, 10).expect("REASON");
                    mov_1.src =
                        AsmAstOperand {
                            operand_type: AsmAstOperandType::Imm(converted_value)
                        };
                }

                // // TODO: convert base on number system
                // // (binary, octal, decimal, hexadecimal! Currently hard-coded!)
                // // this is the value that is assigned to the array element
                // let val = i32::from_str_radix(&literal_value, 10).expect("REASON");
                // mov_1.src = AsmAstOperand { operand_type: AsmAstOperandType::Imm(val) };
            }
            _ => {
                panic!("Need variable! Got {:?}", &tacky_instruction_subscript.src);
            }
        }

        // dest is the element of the array to copy source into
        match &tacky_instruction_subscript.dst {
            ValueElement::Variable(var_name) => {
                // DEBUG
                if self.debug {
                    println!("[Tacky2Inter] var_name:'{:?}'", var_name);
                }
                mov_1.dst = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                // when the src has a base address and an offset! such as in 'int x = arr[i];'
                // Here i is the offset applied to the base address which is the address of arr.
                mov_1.offset = AsmAstOperand { operand_type: AsmAstOperandType::Reg(offset_register.clone()) };
            }
            ValueElement::Constant(constant_value) => {
                mov_1.dst = AsmAstOperand { operand_type: AsmAstOperandType::Imm(i32::from_str_radix(&constant_value, 10).expect("REASON")) };
            }
            _ => {
                panic!("Need variable or constant! Got {:?}", &tacky_instruction_subscript.src);
            }
        }
        assert_ne!(mov_1.assembly_type, AstAstAssemblyType::Unknown);
        asm_ast_function.body.push(Box::new(mov_1));
    }

    pub fn visit_tacky_add_assignment(&mut self,
        asm_ast_function: &mut AsmAstFunction,
        instruction: &Instruction)
    {
        //
        // a += 123;
        //
        // Converted to
        //
        // mov rax, DWORD PTR [rsp+???]
        // add 123
        // mov DWORD PTR [rsp+???], rax
        //
        // It is allowed to immediately add a value to a memory location in x86-64
        //
        // add DWORD PTR [rbp-4], 123
        //

        let mut assignment_instruction: AsmAstInstruction = AsmAstInstruction::new();
        assignment_instruction.instruction_type = AsmAstInstructionType::Unary;
        assignment_instruction.unary_operator = AsmAstUnaryOperator::AddAssignment;
        assignment_instruction.comment = String::from(format!("    ; add for AddAssignment (e.g. a += 123;)").to_string());

        // source
        // set data type and also set the object that is used as source
        let mut src_data_type: DataType = DataType::DataTypeUnknown;
        match &instruction.src {
            ValueElement::Variable(var_name) => {
                let symbol_table_entry_option = self.symbol_table.borrow_mut().get(var_name);
                src_data_type = symbol_table_entry_option.expect(format!("No symbol for '{}' found in symbol table!\n", var_name).as_str()).data_type;
                assignment_instruction.src = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                assignment_instruction.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
            }
            ValueElement::Constant(constant_value) => {
                src_data_type = DataType::DataTypeInt; // TODO: how to determine the type of the constant?
                assignment_instruction.src = AsmAstOperand { operand_type: AsmAstOperandType::Imm(i32::from_str_radix(&constant_value, 10).expect("REASON")) };
                assignment_instruction.src_2 = AsmAstOperand { operand_type: AsmAstOperandType::Imm(i32::from_str_radix(&constant_value, 10).expect("REASON")) };
            }
            _ => {
                unimplemented!()
            }
        }
        assignment_instruction.assembly_type = AstAstAssemblyType::from_data_type(&src_data_type);

        // destination
        match &instruction.dst {
            ValueElement::Variable(var_name) => {
                assignment_instruction.dst = AsmAstOperand { operand_type: AsmAstOperandType::Pseudo(var_name.clone()) };
                // assignment_instruction.dst = AsmAstOperand { operand_type: AsmAstOperandType::Memory(var_name.clone(), 0) };
            }
            _ => {
                unimplemented!()
            }
        }

        assert_ne!(assignment_instruction.assembly_type, AstAstAssemblyType::Unknown);

        // DEBUG
        // println!("[Tacky2Intermediate] assignment_instruction:\n{:?}", assignment_instruction);

        asm_ast_function.body.push(Box::new(assignment_instruction));
    }

